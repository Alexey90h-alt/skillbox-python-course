# Инициализация переменных
number = 1.0  # Стартовое значение
count = 0     # Счетчик итераций

# Цикл деления до потери точности
while number > 0:
    number = number / 2
    count += 1

# Вывод результата
print(f"Итоговое количество делений: {count}")
print(f"Значение после выхода из цикла: {number}")