def check_tax_impact():
    """
    Проверяет, достаточно ли велик новый налог, чтобы изменить бюджет страны.
    Демонстрирует ограничения точности чисел с плавающей точкой (float).
    """
    print("--- Бухгалтерская проверка бюджета ---")
    
    try:
        # Ввод данных в экспоненциальной форме (например, 1.23e12)
        total_tax = float(input("Введите бюджет страны: "))
        new_tax = float(input("Новые поступления (налог): "))

        # Магия проверки: изменится ли сумма при сложении?
        if total_tax + new_tax > total_tax:
            print("Результат: Бюджет увеличится ✅")
        else:
            print("Результат: Бюджет не изменится ❌")
            
    except ValueError:
        print("Ошибка: пожалуйста, вводите числа в формате 1.2e12")